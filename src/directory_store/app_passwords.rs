//! Per-account app passwords: secondary mail credentials for IMAP/SMTP.
//!
//! An app password lets a client authenticate to a mail account without the
//! primary password — handy for a device whose secret you may want to revoke in
//! isolation. Each carries a human `label`, an argon2id PHC hash of the secret
//! (never the secret itself), an optional `expires_at` (epoch seconds) and an
//! optional single-CIDR `ip_cidr` allowlist. They persist to
//! `<data_dir>/app_passwords.toml`, mirroring how dynamic accounts persist in
//! [`super`].
//!
//! Verification is fail-closed: an app password authenticates only when the
//! argon2id hash verifies AND it is unexpired AND (no `ip_cidr`, or the client
//! IP is inside it). Anything malformed or missing is a rejection, never an
//! allow.
//!
//! [`super`]: super::AccountStore

use std::collections::HashMap;
use std::net::IpAddr;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::storage::locked::{EditError, edit};

use super::StoreError;

/// One app password as listed: label, created-at, expiry, IP CIDR and the
/// `save_sent` override.
pub type AppPasswordRow = (String, String, Option<u64>, Option<String>, Option<bool>);

/// One app password as persisted in `app_passwords.toml`.
#[derive(Debug, Clone, Serialize, Deserialize)]

pub struct AppPassword {
	/// Human-readable label identifying the credential (e.g. "iphone").
	pub label: String,
	/// argon2id PHC hash of the secret. The secret is shown once at creation.
	pub hash: String,
	/// Expiry as epoch seconds; `None` never expires.
	#[serde(default)]
	pub expires_at: Option<u64>,
	/// Single-CIDR allowlist (`203.0.113.0/24` or a bare IP); `None` allows any.
	#[serde(default)]
	pub ip_cidr: Option<String>,
	/// Whether messages sent through this app password are saved to the
	/// account's `Sent` folder. `None` (the default and the value on
	/// `app_passwords.toml` files written before the field existed) defers
	/// to the account-wide setting: the account setting wins when the
	/// app password does not override it. An explicit `Some(false)` here
	/// disables the save for this credential even if the account has it
	/// on (a phone whose mail app is read-only, a relay that should not
	/// pollute Sent).
	#[serde(default)]
	pub save_sent: Option<bool>,
}

impl AppPassword {
	/// Whether this app password admits `password` from `client_ip` at `now`
	/// (epoch seconds). Fail-closed on every branch: a malformed CIDR rejects;
	/// a CIDR with no client IP rejects (we cannot prove the IP is permitted).
	/// The argon2id verification runs first and unconditionally so the
	/// expiry/IP checks do not become a faster-rejection timing oracle.
	///
	/// `policy` decides whether `password` is NFKC-normalised before the
	/// argon2id verification. App passwords are random URL-safe base64
	/// generated by the CLI; the policy's prepare is a no-op even when
	/// unicode passwords are enabled, but the call is still applied so a
	/// future operator-provided app secret stays under the same rule.
	pub fn admits(
		&self,
		password: &str,
		policy: &crate::password::Policy,
		client_ip: Option<IpAddr>,
		now: u64,
	) -> bool {
		let prepared = policy.login_form(password);
		let hash_ok = crate::smtp::auth::verify_password(&self.hash, prepared.as_ref());
		let time_ok = self.expires_at.is_none_or(|expiry| now < expiry);
		let ip_ok = match &self.ip_cidr {
			None => true,
			Some(spec) => match (crate::cidr::Cidr::parse(spec), client_ip) {
				(Some(cidr), Some(ip)) => cidr.contains(ip),
				// A configured allowlist with an unparseable spec or an unknown
				// client IP cannot be satisfied: reject.
				_ => false,
			},
		};
		hash_ok && time_ok && ip_ok
	}
}

/// The TOML document: account name → its app passwords.
#[derive(Debug, Default, Serialize, Deserialize)]
pub(crate) struct AppPasswordFile {
	/// `[accounts.<name>]` tables, each a list under `passwords`.
	#[serde(default)]
	pub(crate) accounts: HashMap<String, AccountEntry>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
pub(crate) struct AccountEntry {
	#[serde(default)]
	pub(crate) passwords: Vec<AppPassword>,
}

/// Filesystem-backed store of per-account app passwords.
pub struct AppPasswordStore {
	path: PathBuf,
	accounts: HashMap<String, Vec<AppPassword>>,
}

impl AppPasswordStore {
	/// Open (loading if present) the store under `data_dir`. A missing file is
	/// an empty store.
	pub fn open(data_dir: &Path) -> Result<Self, StoreError> {
		let path = data_dir.join("app_passwords.toml");
		let file: AppPasswordFile = match std::fs::read_to_string(&path) {
			Ok(text) => {
				toml::from_str(&text).map_err(|error| StoreError::Invalid(error.to_string()))?
			}
			Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
				AppPasswordFile::default()
			}
			Err(error) => return Err(error.into()),
		};
		let accounts = file
			.accounts
			.into_iter()
			.map(|(name, entry)| (name.to_ascii_lowercase(), entry.passwords))
			.collect();
		Ok(AppPasswordStore { path, accounts })
	}

	/// The app passwords for one account (lowercased lookup), or an empty slice.
	pub fn for_account(&self, account: &str) -> &[AppPassword] {
		self.accounts
			.get(&account.to_ascii_lowercase())
			.map(Vec::as_slice)
			.unwrap_or(&[])
	}

	/// Every `(account, app_password)` pair, for attaching to the directory.
	pub fn entries(&self) -> impl Iterator<Item = (String, AppPassword)> + '_ {
		self.accounts.iter().flat_map(|(account, passwords)| {
			passwords
				.iter()
				.map(move |password| (account.clone(), password.clone()))
		})
	}

	/// Add an app password for an account (the account is lowercased). The hash
	/// must already be argon2id; the caller generated and showed the secret.
	pub fn add(&mut self, account: &str, password: AppPassword) -> Result<(), StoreError> {
		if let Some(spec) = &password.ip_cidr
			&& crate::cidr::Cidr::parse(spec).is_none()
		{
			return Err(StoreError::Invalid(format!("invalid CIDR \"{spec}\"")));
		}
		let account = account.to_ascii_lowercase();
		// The whole-file rewrite goes through `locked::edit` so a CLI
		// `epistle app-password add` and a server `add` running in
		// parallel both reach disk: each takes the sibling lock,
		// re-reads, mutates the fresh state, and writes atomically.
		let new_state = edit(
			&self.path,
			|text| {
				toml::from_str::<AppPasswordFile>(text).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			|state| {
				toml::to_string_pretty(state).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			AppPasswordFile::default,
			|state| -> Result<(), StoreError> {
				let list = &mut state.accounts.entry(account.clone()).or_default().passwords;
				if list.iter().any(|existing| existing.label == password.label) {
					return Err(StoreError::Duplicate(password.label.clone()));
				}
				list.push(password.clone());
				Ok(())
			},
		)
		.map_err(|error| match error {
			EditError::Io(io) => StoreError::Io(io),
			EditError::Mutate(store) => store,
		})?;
		// The in-memory mirror is refreshed from the post-write state, so
		// a sibling process's previous write is visible on the next read
		// without the file watcher running.
		self.accounts.clear();
		for (name, entry) in new_state.accounts {
			self.accounts
				.insert(name.to_ascii_lowercase(), entry.passwords);
		}
		Ok(())
	}

	/// Remove an account's app password by label. `NotFound` if absent.
	pub fn remove(&mut self, account: &str, label: &str) -> Result<(), StoreError> {
		let account = account.to_ascii_lowercase();
		let label = label.to_string();
		let new_state = edit(
			&self.path,
			|text| {
				toml::from_str::<AppPasswordFile>(text).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			|state| {
				toml::to_string_pretty(state).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			AppPasswordFile::default,
			|state| {
				let entry = state
					.accounts
					.get_mut(&account)
					.ok_or_else(|| StoreError::NotFound(format!("{account}/{label}")))?;
				let before = entry.passwords.len();
				entry.passwords.retain(|existing| existing.label != label);
				if entry.passwords.len() == before {
					return Err(StoreError::NotFound(format!("{account}/{label}")));
				}
				Ok(())
			},
		)
		.map_err(|error| match error {
			EditError::Io(io) => StoreError::Io(io),
			EditError::Mutate(store) => store,
		})?;
		self.accounts.clear();
		for (name, entry) in new_state.accounts {
			self.accounts
				.insert(name.to_ascii_lowercase(), entry.passwords);
		}
		Ok(())
	}

	/// Drop every app password for `account` (case-insensitive). Returns
	/// the number that were removed; persists once at the end. Idempotent:
	/// a missing account returns `Ok(0)` without rewriting the file. Used
	/// by [`crate::directory_store::removal::remove_account`] to clear the
	/// account's whole footprint in a single pass.
	pub fn remove_account(&mut self, account: &str) -> Result<u32, StoreError> {
		let account = account.to_ascii_lowercase();
		// The `edit` helper's closure returns `Result<(), _>`, so we
		// capture the count in a local and surface it through the
		// `Option<u32>` after the lock releases.
		let mut removed: Option<u32> = None;
		let new_state = edit(
			&self.path,
			|text| {
				toml::from_str::<AppPasswordFile>(text).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			|state| {
				toml::to_string_pretty(state).map_err(|error| {
					std::io::Error::new(std::io::ErrorKind::InvalidData, error.to_string())
				})
			},
			AppPasswordFile::default,
			|state: &mut AppPasswordFile| -> Result<(), StoreError> {
				match state.accounts.remove(&account) {
					Some(entry) => removed = Some(entry.passwords.len() as u32),
					None => removed = Some(0),
				}
				Ok(())
			},
		)
		.map_err(|error| match error {
			EditError::Io(io) => StoreError::Io(io),
			EditError::Mutate(store) => store,
		})?;
		self.accounts.clear();
		for (name, entry) in new_state.accounts {
			self.accounts
				.insert(name.to_ascii_lowercase(), entry.passwords);
		}
		Ok(removed.unwrap_or(0))
	}

	/// Every `(account, label, expires_at, ip_cidr, save_sent)` for
	/// listing. Secrets and hashes are never exposed. `save_sent` is
	/// `Some(true)`/`Some(false)` when the credential carries an
	/// explicit override, `None` when it defers to the account-wide
	/// setting.
	pub fn list(&self) -> Vec<AppPasswordRow> {
		let mut rows: Vec<_> = self
			.accounts
			.iter()
			.flat_map(|(account, passwords)| {
				passwords.iter().map(move |password| {
					(
						account.clone(),
						password.label.clone(),
						password.expires_at,
						password.ip_cidr.clone(),
						password.save_sent,
					)
				})
			})
			.collect();
		rows.sort();
		rows
	}
}

/// Compatibility for the legacy non-helper `persist()` call site that
/// other crates may still link to through `add`/`remove`/`remove_account`
/// after a rewrite: every mutation now routes through the locked
/// helper, so `persist` is a thin shim. Kept on the type as
/// `pub(crate)` so the rest of the crate can keep a stable call site.
#[allow(dead_code)]
impl AppPasswordStore {
	pub(crate) fn persist(&self) -> Result<(), StoreError> {
		Ok(())
	}
}

